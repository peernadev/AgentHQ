import { randomUUID } from "node:crypto";
import type { Content } from "@google/genai";
import { HttpError } from "../http";
import { parseTaskBatch, type ParsedTask } from "../task-input";
import { jsonSession } from "./gemini";
import { checkNarrowScopes, checkParallelOverlap, checkRealPaths, checkTaskCount, MIN_PLAN_TASKS } from "./plan-checks";
import context from "./repo-context.json"; // generated by scripts/gen-repo-context.mjs
