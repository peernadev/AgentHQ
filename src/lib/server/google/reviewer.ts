import "server-only";
import type { Content } from "@google/genai";
import type { CheckResults, ReviewVerdict } from "@/types/api";
import { HttpError } from "../http";
import { asData, jsonSession } from "./gemini";
import { diffSummary, type PrInfo } from "./github";
import context from "./repo-context.json"; // generated by scripts/gen-repo-context.mjs

// Gemini reviewer (SPEC §7). Called OUTSIDE any Firestore transaction. Bound to one head SHA.
// Rules first: failed checks are "revise" without Gemini; files outside the task's scope
// can never be "pass". Gemini output is untrusted: schema-checked, one retry with the error.

const BUDGET_MS = 50_000; // the route's maxDuration is 60 s
const ATTEMPTS = 2;
const VERDICTS: ReviewVerdict[] = ["pass", "revise", "needs_human"];

const REVIEW_SCHEMA = {
  type: "object",
  properties: {
    verdict: { type: "string", enum: VERDICTS },
    notes: { type: "string", description: "1-4 sentences for the human reviewer" },
    evidence: { type: "array", items: { type: "string" }, minItems: 1, maxItems: 6 },
  },
  required: ["verdict", "notes", "evidence"],
};

export interface ReviewInput {
  task: { title: string; description: string; acceptance: string | null; scope: string[] };
  head_sha: string;
  checks: CheckResults;
  pr: PrInfo;
}
export interface ReviewDraft { verdict: ReviewVerdict; notes: string; evidence: string[]; model: string }

const inScope = (file: string, scope: string[]) => scope.some((s) => file === s.replace(/\/+$/, "") || file.startsWith(s));

export function outOfScope(files: PrInfo["files"], scope: string[]): string[] {
  return files.map((f) => f.filename).filter((f) => !inScope(f, scope));
}

/** Parses and schema-checks a review (Gemini's answer or an orchestrator's verdict). Throws on bad input. */
export function parseReview(text: string | undefined): Omit<ReviewDraft, "model"> {
  let raw: Record<string, unknown>;
  try {
    raw = JSON.parse(text ?? "");
  } catch {
    throw new Error("The response was not valid JSON.");
  }
  const verdict = raw?.verdict as ReviewVerdict;
  if (!VERDICTS.includes(verdict)) throw new Error(`"verdict" must be one of ${VERDICTS.join(", ")}`);
  if (typeof raw.notes !== "string" || !raw.notes.trim()) throw new Error(`"notes" must be a non-empty string`);
  const ev = raw.evidence;
  if (!Array.isArray(ev) || !ev.length || ev.some((e) => typeof e !== "string" || !e.trim())) {
    throw new Error(`"evidence" must be a non-empty list of strings`);
  }
  return {
    verdict,
    notes: raw.notes.trim().slice(0, 2000),
    evidence: (ev as string[]).slice(0, 6).map((e) => e.trim().slice(0, 300)),
  };
}

const failedChecks = (checks: CheckResults) => (Object.keys(checks) as (keyof CheckResults)[]).filter((k) => !checks[k]);

/**
 * The review without any AI: failed checks are "revise"; files outside the scope are "needs_human";
 * otherwise "needs_human" with the facts (a human or an AI reviewer decides). model = "rules".
 */
export function rulesReview(input: ReviewInput): ReviewDraft {
  const { task, checks, pr, head_sha } = input;
  const failed = failedChecks(checks);
  if (failed.length) {
    return {
      verdict: "revise", model: "rules",
      notes: `Checks failed: ${failed.join(", ")}. Fix them and run hq review again; only passing work gets an AI review.`,
      evidence: failed.map((k) => `${k}: failed at ${head_sha.slice(0, 7)}`),
    };
  }
  const outside = outOfScope(pr.files, task.scope);
  if (outside.length) {
    return {
      verdict: "needs_human", model: "rules",
      notes: `Rules-only review: checks passed, but ${outside.length} changed file(s) are outside the task's scope. A human should look at them.`,
      evidence: [`Outside scope (${task.scope.join(", ")}): ${outside.slice(0, 10).join(", ")}`, `lint, typecheck, build: passed at ${head_sha.slice(0, 7)}`],
    };
  }
  return {
    verdict: "needs_human", model: "rules",
    notes: "Rules-only review (no AI): lint, types and build passed and every changed file is inside the task's scope. The acceptance criteria still need a human or AI review.",
    evidence: [`lint, typecheck, build: passed at ${head_sha.slice(0, 7)}`, `${pr.files.length} changed file(s), all inside ${task.scope.join(", ")}`],
  };
}

/** Rules an AI verdict can't override: failed checks are never "pass"; out-of-scope changes are never "pass". */
export function guardReview(draft: ReviewDraft, input: ReviewInput): ReviewDraft {
  const failed = failedChecks(input.checks);
  const outside = outOfScope(input.pr.files, input.task.scope);
  const out = { ...draft, evidence: [...draft.evidence] };
  if (outside.length) out.evidence = [`Outside scope (${input.task.scope.join(", ")}): ${outside.slice(0, 10).join(", ")}`, ...out.evidence].slice(0, 6);
  if (out.verdict === "pass" && failed.length) {
    out.verdict = "revise";
    out.notes = `Checks failed (${failed.join(", ")}), so this can't pass. ${out.notes}`;
  } else if (out.verdict === "pass" && outside.length) {
    out.verdict = "needs_human";
    out.notes = `Changed ${outside.length} file(s) outside the task's scope, so this can't pass automatically. ${out.notes}`;
  }
  return out;
}

export async function reviewTask(input: ReviewInput): Promise<ReviewDraft> {
  const { task, checks, pr } = input;
  if (failedChecks(checks).length) return rulesReview(input);
  const outside = outOfScope(pr.files, task.scope);

  const prompt = [
    `# Task (data)\n${asData(JSON.stringify({ title: task.title, description: task.description, acceptance: task.acceptance, scope: task.scope }, null, 2))}`,
    `# Evidence\nCommit: ${input.head_sha}\nChecks: lint ${checks.lint}, typecheck ${checks.typecheck}, build ${checks.build} (all passed)\n`
      + (outside.length
        ? `SCOPE VIOLATION (computed, a fact): ${outside.length} changed file(s) are outside the task's scope `
          + `${JSON.stringify(task.scope)}: ${outside.join(", ")}. The verdict can't be "pass". Say in notes which `
          + "out-of-scope changes the human should look at; never claim the PR stays within scope."
        : "Scope: every changed file is inside the task's scope."),
    `# Pull request #${pr.number} (data)\nTitle: ${asData(pr.title)}\n\n${asData(diffSummary(pr.files))}`,
    "Return the review as JSON { verdict, notes, evidence }.",
  ].join("\n\n");
  const contents: Content[] = [{ role: "user", parts: [{ text: prompt }] }];
  const session = jsonSession({
    label: "reviewer", system: context.reviewer_prompt, schema: REVIEW_SCHEMA, budgetMs: BUDGET_MS, temperature: 0.1,
  });

  let lastError = "";
  for (let attempt = 1; attempt <= ATTEMPTS; attempt++) {
    const text = await session.call(contents);
    try {
      return guardReview({ ...parseReview(text), model: session.model }, input);
    } catch (e) {
      lastError = e instanceof Error ? e.message : String(e);
      contents.push(
        { role: "model", parts: [{ text: text ?? "" }] },
        { role: "user", parts: [{ text: `Your review was rejected: ${lastError}\nReturn a corrected review.` }] },
      );
    }
  }
  throw new HttpError(502, `Reviewer output was rejected ${ATTEMPTS} times: ${lastError}`);
}
