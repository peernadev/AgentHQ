import "server-only";
import type { Content } from "@google/genai";
import type { RecoveryKind, TaskSize } from "@/types/api";
import { HttpError } from "../http";
import type { ParsedTask } from "../task-input";
import { asData, jsonSession } from "./gemini";
import { TASK_SCHEMA, validate } from "./planner";
import context from "./repo-context.json"; // generated by scripts/gen-repo-context.mjs

// Recovery planner (SPEC §7): one smaller fix task, or a prerequisite, from a failed task's
// reason and log. Called OUTSIDE any Firestore transaction. Output is untrusted: same
// validation as planner tasks, plus scope/size rules; one retry with the rejection reason.

const BUDGET_MS = 50_000;
const ATTEMPTS = 2;
const KINDS: RecoveryKind[] = ["fix", "prerequisite"];
const SIZE_RANK: Record<TaskSize, number> = { S: 1, M: 2, L: 4 };

const RECOVERY_SCHEMA = {
  type: "object",
  properties: { kind: { type: "string", enum: KINDS }, task: TASK_SCHEMA },
  required: ["kind", "task"],
};

export interface FailedTask {
  id: string; title: string; description: string; acceptance: string | null; scope: string[]; size: TaskSize;
}
export interface RecoveryInput {
  failed: FailedTask; reason: string; log_excerpt: string | null;
  queueIds: Set<string>; locks: Record<string, string[]>;
}
export interface RecoveryDraft { kind: RecoveryKind; task: ParsedTask; model: string }

const overlap = (a: string[], b: string[]) => a.some((x) => b.some((y) => x.startsWith(y) || y.startsWith(x)));

/** Validates one answer. Throws an Error whose message is fed back to Gemini on retry. */
export function validateRecovery(text: string | undefined, input: RecoveryInput): Omit<RecoveryDraft, "model"> {
  let raw: { kind?: unknown; task?: unknown };
  try {
    raw = JSON.parse(text ?? "");
  } catch {
    throw new Error("The response was not valid JSON.");
  }
  const kind = raw?.kind as RecoveryKind;
  if (!KINDS.includes(kind)) throw new Error(`"kind" must be "fix" or "prerequisite"`);
  // The planner's validation (schema, real paths, dependencies), minus its plan-level quality
  // rules (strict: false): a recovery is a single task, which the 5-task minimum would reject.
  const [task] = validate(JSON.stringify({ tasks: [raw.task] }), input.queueIds, { strict: false });
  const { failed } = input;
  const errors: string[] = [];
  if (task.depends_on.includes(failed.id)) errors.push("Don't depend on the failed task");
  if (SIZE_RANK[task.size ?? "M"] > SIZE_RANK[failed.size]) {
    errors.push(`size ${task.size} is larger than the failed task's size ${failed.size}`);
  }
  if (kind === "fix") {
    const outside = task.scope.filter((s) => !failed.scope.some((f) => s.startsWith(f)));
    if (outside.length) errors.push(`a fix must stay inside the failed task's scope (${failed.scope.join(", ")}); outside: ${outside.join(", ")}`);
  } else {
    const held = Object.entries(input.locks).filter(([id, scope]) => id !== failed.id && overlap(scope, task.scope));
    if (held.length) errors.push(`scope overlaps locks held by tasks ${held.map(([id]) => id).join(", ")}`);
  }
  if (errors.length) throw new Error(errors.slice(0, 10).join("\n"));
  return { kind, task };
}

export async function draftRecovery(input: RecoveryInput): Promise<RecoveryDraft> {
  const { failed } = input;
  const prompt = [
    `# Failed task (data)\n${asData(JSON.stringify({
      title: failed.title, description: failed.description, acceptance: failed.acceptance, scope: failed.scope, size: failed.size,
    }, null, 2))}`,
    `# Failure reason (data)\n${asData(input.reason)}`,
    `# Last lines of the failing check (data)\n${input.log_excerpt ? asData(input.log_excerpt) : "(none attached)"}`,
    `# Ownership (from AGENTS.md)\n${context.ownership}`,
    `# Repo file tree${context.truncated ? " (truncated)" : ""}\n${context.files.join("\n")}`,
    `# Scope locks held now ({ taskId: scope })\n${JSON.stringify(input.locks)}`,
    "Return JSON { kind, task }.",
  ].join("\n\n");
  const contents: Content[] = [{ role: "user", parts: [{ text: prompt }] }];
  const session = jsonSession({ label: "recovery", system: context.recovery_prompt, schema: RECOVERY_SCHEMA, budgetMs: BUDGET_MS });

  let lastError = "";
  for (let attempt = 1; attempt <= ATTEMPTS; attempt++) {
    const text = await session.call(contents);
    try {
      return { ...validateRecovery(text, input), model: session.model };
    } catch (e) {
      lastError = e instanceof Error ? e.message : String(e);
      contents.push(
        { role: "model", parts: [{ text: text ?? "" }] },
        { role: "user", parts: [{ text: `Your recovery task was rejected:\n${lastError}\nReturn a corrected answer.` }] },
      );
    }
  }
  throw new HttpError(502, `Recovery output was rejected ${ATTEMPTS} times: ${lastError}`);
}
